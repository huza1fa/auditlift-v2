async function ensureDocumentUploaded(resource: string): Promise<string> {
	const doc = documents[resource];
	const exists = await fileExists(doc.storageKey);
	if (!exists) {
		const buffer = Buffer.from(doc.content, 'utf-8');
		await uploadBuffer(doc.storageKey, buffer, 'text/markdown');
	}
	return getPresignedDownloadUrl(doc.storageKey, 60 * 60); // 1 hour expiry
}

export const POST: RequestHandler = async ({ request, locals, getClientAddress }) => {
	const body = await request.json();
	const { name, email, company, resource } = body;

	if (!name || typeof name !== 'string' || name.trim().length === 0) {
		throw error(400, 'Name is required');
	}
	if (!email || typeof email !== 'string' || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
		throw error(400, 'A valid email is required');
	}
	if (!resource || !documents[resource]) {
		throw error(400, 'Invalid resource');
	}

	// Rate limit: 5 submissions per IP per hour
	const ip = getClientAddress();
	if (!checkRateLimit(`lead-magnet:${ip}`, 5, 60 * 60 * 1000)) {
		throw error(429, 'Too many requests. Please try again later.');
	}

	const organizationId = locals.organizationId ?? null;
	const normalizedEmail = email.trim().toLowerCase();

	await db.insert(consultingRequests).values({
		organizationId,
		name: name.trim(),
		email: normalizedEmail,
		company: company?.trim() || null,
		topic: `lead-magnet-${resource}`,
		message: `Lead magnet download requested: ${resource}`
	});

	await captureServerEvent({
		event: 'lead_magnet_downloaded',
		properties: {
			resource,
			org_id: organizationId,
			is_logged_in: !!locals.session
		},
		groups: organizationId ? { organization: organizationId } : undefined
	});

	// Notify team (fire-and-forget)
	sendLeadMagnetNotification({
		name: name.trim(),
		email: normalizedEmail,
		company: company?.trim() || null,
		resource,
		organizationId,
		isLoggedIn: !!locals.session
	}).catch((err) => console.error('[lead-magnet] Notification failed:', err));

	// Ensure document is in S3 and return presigned URL (fallback to inline base64 in dev)
	let downloadUrl: string;
	try {
		downloadUrl = await ensureDocumentUploaded(resource);
	} catch (s3Err) {
		console.warn('[lead-magnet] S3 upload failed, falling back to inline download:', s3Err);
		const doc = documents[resource];
		const buffer = Buffer.from(doc.content, 'utf-8');
		const base64 = buffer.toString('base64');
		downloadUrl = `data:text/markdown;base64,${base64}`;
	}

	return json({ success: true, downloadUrl, filename: documents[resource].filename });
};
